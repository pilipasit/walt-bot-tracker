import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const context = { window: {} };
vm.runInNewContext(readFileSync(new URL('../extras.js', import.meta.url), 'utf8'), context);
const { funding, journalMath, summary, backtestLine, backtestPeriod } = context.window.WaltExtras;
assert.ok(Math.abs(funding(.0001, -1, 1000, 24) - 2.4) < 1e-9);
assert.ok(Math.abs(funding(.0001, 1, 1000, 24) + 2.4) < 1e-9);
assert.equal(funding(null, 1, 1000, 24), null);
const trade = journalMath({ side: 1, size: 1000, entry: 100, sl: 90, fee: 1, opened: '2026-01-01T00:00:00Z' }, 110, .1, Date.parse('2026-01-02T00:00:00Z'));
assert.ok(Math.abs(trade.pnl - 97.9) < 1e-9);
assert.ok(Math.abs(trade.r - 97.9 / 101.9) < 1e-9);
assert.equal(trade.hours, 24);
const counts = summary([{analysis:{trend:'down',aligned:true}},{analysis:{trend:'up'}},{analysis:{trend:'sideways'}},{analysis:null}]);
assert.equal(JSON.stringify(counts), JSON.stringify({up:1,down:1,sideways:1,aligned:1}));
const oldSummary = {paired_episodes: 8, paired_tp_rate: .25, random_tp_rate: .2, episode: {completed: 10, avg_pnl_pct: -.2}};
const oldLine = backtestLine(oldSummary, 'Historical rule');
assert.match(oldLine, /25\.0% vs 20\.0% random \(8 paired entries\)/);
assert.match(oldLine, /avg P\/L -0\.20% \(10 completed trades\)/);
const pairedLine = backtestLine({...oldSummary, paired_avg_pnl_pct: .1, random_avg_pnl_pct: -.15}, 'Rule');
assert.match(pairedLine, /avg P\/L \+0\.10% vs -0\.15% random \(8 paired entries\)/);
assert.equal(backtestPeriod({}), 'Historical snapshot; data dates unavailable.');
assert.equal(backtestPeriod({coverage: {from:'2026-08-20T00:00:00Z', to:'2026-11-20T00:00:00Z'}}), 'Historical candle coverage: 2026-08-20 to 2026-11-20 UTC; individual assets may differ. Generation date unavailable.');
assert.match(backtestPeriod({generated_at:'2026-11-20T10:00:00Z', coverage: {from:'2026-08-20T00:00:00Z', to:'2026-11-20T00:00:00Z'}}), /Generated 2026-11-20 UTC/);
console.log('extras tests passed');
